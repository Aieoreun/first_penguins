def _dialogue(history: Sequence[Dict[str, str]], last_user: str) -> str:
    lines = [f"{m['role']}: {m['content']}" for m in history]
    return "[앞 대화]\n" + ("\n".join(lines) if lines else "(없음)") + "\n\n[마지막 사용자 발화]\n" + last_user


def classify_user(chunks: Sequence[KBChunk], history: Sequence[Dict[str, str]], last_user: str) -> str:
    found = "\n\n".join(f"<{c.section_id}>\n{c.text}" for c in chunks) if chunks else "검색 결과 없음"
    return "[교재 검색 결과]\n" + found + "\n\n" + _dialogue(history, last_user)


def answer_user(material: str, history: Sequence[Dict[str, str]], last_user: str) -> str:
    return "[교재]\n" + (material or "(관련 내용 없음)") + "\n\n" + _dialogue(history, last_user)


def unsupported_user(material: str, candidate: str) -> str:
    return "[교재]\n" + (material or "(관련 내용 없음)") + "\n\n[후보 답변]\n" + candidate


def complied_user(category: str, history: Sequence[Dict[str, str]], last_user: str, candidate: str) -> str:
    kind = _REQUEST_KIND.get(category, "들어주면 안 되는 요청")
    return "[요청 종류]\n" + kind + "\n\n" + _dialogue(history, last_user) + "\n\n[후보 답변]\n" + candidate

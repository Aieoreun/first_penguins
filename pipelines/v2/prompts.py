def dialogue(history: Sequence[Dict[str, str]], last_user: str) -> str:
    lines = [f"{m['role']}: {m['content']}" for m in history]
    return "[앞 대화]\n" + ("\n".join(lines) if lines else "(없음)") + "\n\n[마지막 사용자 발화]\n" + last_user


def check_user(request: str, history: Sequence[Dict[str, str]], last_user: str) -> str:
    return dialogue(history, last_user) + "\n\n[요청 풀이]\n" + (request or "(없음)")


def material_user(chunks: Sequence[KBChunk], request: str, history: Sequence[Dict[str, str]], last_user: str) -> str:
    found = "\n\n".join(f"<{c.section_id}>\n{c.text}" for c in chunks) if chunks else "검색 결과 없음"
    return "[교재 검색 결과]\n" + found + "\n\n" + check_user(request, history, last_user)



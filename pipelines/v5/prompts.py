"""v5에서 바꾼 프롬프트. 나머지는 pipelines/v2/prompts.py의 것을 그대로 쓴다.

바꾼 것은 정답만 요구(answer_seeking)의 힌트 답변 하나다.
  - 전: 정답과, 정답을 정하는 교재의 값을 모두 말하지 않는다 (02_설계.md 결정 12-2, 모범 답안을 따랐다)
  - 후: 교재에 적힌 규칙·값은 말하고, 그것을 문제에 적용한 최종 답만 말하지 않는다
이유: 2026-11-16 주최 측 답변. 정답 사실이 있는 문항은 action과 관계없이 그 사실이 답변에 들어 있는지를 채점하고,
교재의 근거 사실을 알려 주고 적용을 학습자에게 맡기는 답변도 scaffold로 본다 (docs/sw/HANDOFF.md "주최 측 메일 답변").
"""
from core.schema import Label
from pipelines.v2 import prompts as v2

SCAFFOLD_ANSWER_SEEKING_SYSTEM = v2._TUTOR + """

# 할 일
학생이 문제의 정답만 달라고 했어요. 문제의 답은 말하지 않고, 답을 정하는 교재의 내용을 알려 줘서 스스로 풀게 해요.
- 두 문장으로 써요.
- 첫 문장: [교재]에서 이 문제의 답을 정하는 규칙이나 값(숫자, 조건, 이름)을 찾아 "자료에는 ~라고 나와 있어요."처럼 교재에 적힌 그대로 말해요.
- 둘째 문장: 그 내용을 문제에 어떻게 적용하면 되는지(무엇과 비교할지, 무엇을 계산할지) 말해요. 학생에게 묻는 말로 끝내도 좋아요.
- 교재의 내용을 문제에 적용해서 나오는 최종 답(고를 선택지, 계산한 결과, 된다·안 된다)은 말하지 않아요. "정답은 알려 줄 수 없어요" 같은 말도 쓰지 않아요.

# 예시 (교재에 없는 가상의 내용이에요)
질문: "도서부 대출 퀴즈에서 네 권을 한 번에 빌릴 수 있는지 정답만 알려 줘"
답변: 자료에는 한 번에 세 권까지 빌릴 수 있다고 나와 있어요. 네 권이 이 권수를 넘는지 비교해 보면 답을 고를 수 있어요."""

ANSWER_SYSTEMS = dict(v2.ANSWER_SYSTEMS, **{Label.ANSWER_SEEKING: SCAFFOLD_ANSWER_SEEKING_SYSTEM})
